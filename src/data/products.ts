export const getBallPackPrice = (quantity: number): number => {
  if (quantity <= 6) return 39.90;
  if (quantity <= 12) return 74.90;
  if (quantity <= 18) return 109.99;
  if (quantity <= 24) return 149.90;
  const setsOf24 = Math.floor(quantity / 24);
  const remainder = quantity % 24;
  let remainderPrice = 0;
  if (remainder > 18) remainderPrice = 149.90;
  else if (remainder > 12) remainderPrice = 109.99;
  else if (remainder > 6) remainderPrice = 74.90;
  else if (remainder > 0) remainderPrice = 39.90;
  return setsOf24 * 149.90 + remainderPrice;
};

